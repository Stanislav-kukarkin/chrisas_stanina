import { create } from 'zustand';
import { ACHIEVEMENTS } from '../domain/achievements';
import { initialPlayer } from './tasks-store.helpers';
import { createGamificationActions } from './slices/gamification-actions';
import { createTaskActions } from './slices/task-actions';
import type { TasksState } from './tasks-store.types';

export type { AppSection, BoardFilter, PlayerState, SyncState } from './tasks-store.types';

export const useTasksStore = create<TasksState>((set, get) => ({
  tasks: [],
  members: [],
  currentUserId: '',
  player: initialPlayer,
  daily: null,
  profiles: [],
  activity: [],
  familyRewards: [],
  inventory: [],
  rewardRequests: [],
  coinTransactions: [],
  sprintHistory: [],
  bossHp: 100,
  bossMaxHp: 100,
  bossName: 'Тыквенный Лентяй',
  bossDescription: '',
  bossQuote: 'Я уже почти начал. Ещё пять минут…',
  bossIcon: '🎃',
  bossTraits: [],
  bossSeason: 'pumpkin',
  bossArchetype: 'Лентяй',
  bossFinalHitUserId: undefined,
  activeSprintId: 'sprint-1',
  sprintNumber: 1,
  sprintEndsAt: undefined,
  syncState: 'loading',
  syncError: null,
  canEdit: false,
  pendingTaskIds: [],
  dailyPending: false,
  shopPending: false,
  activeSection: 'board',
  filter: 'all',
  query: '',
  createModalOpen: false,
  editingTaskId: null,
  toast: null,
  celebration: null,
  setActiveSection: (activeSection) => set({ activeSection }),
  setFilter: (filter) => set({ filter }),
  setQuery: (query) => set({ query }),
  openCreateModal: () => set({ createModalOpen: true, editingTaskId: null }),
  openEditModal: (editingTaskId) => set({ createModalOpen: true, editingTaskId }),
  closeTaskModal: () => set({ createModalOpen: false, editingTaskId: null }),
  dismissToast: () => set({ toast: null }),
  dismissCelebration: () => set({ celebration: null }),
  setSyncState: (syncState, syncError) => set({ syncState, syncError: syncError ?? null }),
  hydrateRemoteBoard: ({
    tasks, profile, boss, history, daily, profiles, activity, familyRewards, inventory,
    rewardRequests, coinTransactions, members, currentUserId, canEdit,
  }) => set((state) => ({
    tasks,
    members: members.length > 0 ? members : [{
      id: currentUserId,
      name: profile.displayName,
      initials: profile.displayName.charAt(0).toLocaleUpperCase('ru-RU') || '•',
      color: '#7c5ce0',
    }],
    currentUserId,
    player: {
      level: profile.level,
      totalXp: profile.totalXp,
      xp: profile.xp,
      xpToNext: profile.xpToNext,
      coins: profile.coins,
      reservedCoins: profile.reservedCoins,
      streaks: profile.streaks,
      streakFreezes: profile.streakFreezes,
      dailyRerollTokens: profile.dailyRerollTokens,
      mysteryChests: profile.mysteryChests,
      openedChests: profile.openedChests,
      shopPurchases: profile.shopPurchases,
      claimedMilestones: profile.claimedMilestones,
      achievementIds: profile.achievementIds,
      activeTitle: profile.activeTitle,
      activeFrame: profile.activeFrame,
      activeEffect: profile.activeEffect,
      activeBackground: profile.activeBackground,
      avatarOverride: profile.avatarOverride,
    },
    daily,
    profiles,
    activity,
    familyRewards,
    inventory,
    rewardRequests,
    coinTransactions,
    sprintHistory: history,
    bossHp: boss.hp,
    bossMaxHp: boss.maxHp,
    bossName: boss.name,
    bossDescription: boss.description,
    bossQuote: boss.quote,
    bossIcon: boss.icon,
    bossTraits: boss.visualTraits,
    bossSeason: boss.season,
    bossArchetype: boss.archetype,
    bossFinalHitUserId: boss.finalHitUserId,
    activeSprintId: boss.sprintId,
    sprintNumber: boss.sprintNumber,
    sprintEndsAt: boss.sprintEndsAt,
    syncState: 'live',
    syncError: null,
    canEdit,
    pendingTaskIds: [],
    dailyPending: false,
    shopPending: false,
    celebration: state.syncState === 'live' && profile.level > state.player.level
      ? { id: Date.now(), kind: 'level', title: `LEVEL ${profile.level}`, detail: 'Новый уровень достигнут! Milestone-награды уже в инвентаре.' }
      : state.syncState === 'live' && profile.achievementIds.some((id) => !state.player.achievementIds.includes(id))
        ? (() => {
          const unlocked = profile.achievementIds.find((id) => !state.player.achievementIds.includes(id));
          const definition = ACHIEVEMENTS.find((item) => item.id === unlocked);
          return {
            id: Date.now(),
            kind: 'achievement' as const,
            title: definition?.name ?? 'Новое достижение',
            detail: definition?.description ?? 'Достижение добавлено в коллекцию.',
          };
        })()
        : state.celebration,
  })),
  ...createTaskActions(set, get),
  ...createGamificationActions(set, get),
}));
